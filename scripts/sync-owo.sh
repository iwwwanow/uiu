#!/usr/bin/env bash
# Собирает owo.css из исходников owo (web/static/css) 1:1, в порядке импортов
# из их index.css. @import шрифтов поднят в начало файла (в склеенном CSS он
# валиден только там). В конец дописывается scripts/owo-deviations.css —
# явно помеченные расхождения с owo, каждое со ссылкой на заметку в бэклоге owo.
#
# Usage: scripts/sync-owo.sh [path-to-owo-repo]   (default: ../iwwwanow_owo)
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OWO="${1:-$REPO_ROOT/../iwwwanow_owo}"
SRC="$OWO/web/static/css"
OUT="$REPO_ROOT/owo.css"

FILES=(
  reset.css
  constants/colors.css
  constants/layout.css
  constants/spaces.css
  scrollbar.css
  layout.css
  font.css
  hr.css
  border.css
  fragments/header.css
  fragments/footer.css
  components/resource-card.css
)

[ -d "$SRC" ] || { echo "owo css not found: $SRC" >&2; exit 1; }
REV="$(git -C "$OWO" rev-parse --short HEAD 2>/dev/null || echo unknown)"

{
  echo "/* ====================================================="
  echo "   owo — styles copied 1:1, deviations marked at the end"
  echo "   source: github.com/iwwwanow/owo @ $REV, web/static/css"
  echo "   generated by scripts/sync-owo.sh — do not edit by hand"
  echo "   ===================================================== */"
  echo
  grep -h '^@import url("https' "$SRC/font.css"
  for f in "${FILES[@]}"; do
    echo
    echo "/* --- $f --- */"
    grep -v '^@import url("https' "$SRC/$f"
  done
  echo
  cat "$REPO_ROOT/scripts/owo-deviations.css"
} > "$OUT"

echo "owo.css ← $SRC @ $REV"
