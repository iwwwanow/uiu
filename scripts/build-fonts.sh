#!/usr/bin/env bash
# Воспроизводимая сборка шрифта Iosevka Term SS14 + Nerd Fonts → assets/fonts/.
#
# Берёт официальный релиз Iosevka (TTF) и официальный FontPatcher Nerd Fonts
# закреплённых версий (sha256 проверяется), патчит нужные начертания со всеми
# иконками (--complete) и сохраняет их в woff2 + iosevka.css + лицензии.
# Те же woff2 служат и для веба, и для системы (scripts/install-fonts.sh).
#
# Начертания: то, что берёт ghostty (Regular, Bold, Italic, BoldItalic),
# плюс LightItalic — чтобы покрыть типографику owo (h6: 300 italic).
#
# Зависимости на хосте: docker, curl, sha256sum. Скачанное кешируется в .cache/fonts/.
# Патчинг идёт в контейнере debian (fontforge + fonttools), образ закреплён по digest.
#
# Usage: scripts/build-fonts.sh
set -euo pipefail

IOSEVKA_VERSION=32.5.0
IOSEVKA_SHA256=dc9901dc366f2ded0649b201192a0a8cd4ad5970caf0dbd5778a0421aeaead1d
NERD_VERSION=3.3.0
NERD_SHA256=ce4284e7d1a8816d29bb3a358e33a44e55804792e7925ed0022ba1b3ab1a9d34
IMAGE=debian:bookworm-slim@sha256:734a72b3d6142a71993b4bc580ca01d8ca687f77a2c422d96a961d3376b179bc
FAMILY="IosevkaTermSS14 Nerd Font"
# fontforge и fonttools берут даты в шрифте отсюда → повторная сборка байт-в-байт
# та же и не даёт diff в git. Дата релиза Iosevka 32.5.0 (2025-01-31).
SOURCE_DATE_EPOCH=1738281600

# имя в релизе Iosevka : файл в assets/fonts : font-weight : font-style
FACES=(
  "Regular:iosevka-regular:400:normal"
  "Bold:iosevka-bold:700:normal"
  "Italic:iosevka-italic:400:italic"
  "BoldItalic:iosevka-bold-italic:700:italic"
  "LightItalic:iosevka-light-italic:300:italic"
)

REPO_ROOT="$(cd "$(dirname "$0")/.." && pwd)"
CACHE="$REPO_ROOT/.cache/fonts"
OUT="$REPO_ROOT/assets/fonts"
mkdir -p "$CACHE" "$OUT"

fetch() { # url sha256 file
  local url=$1 sha=$2 file=$CACHE/$3
  if [ -f "$file" ] && echo "$sha  $file" | sha256sum -c --status; then
    echo "cached: $3"
    return
  fi
  echo "download: $url"
  curl -sSLf -o "$file" "$url"
  echo "$sha  $file" | sha256sum -c --quiet || { echo "sha256 mismatch: $3" >&2; exit 1; }
}

fetch "https://github.com/be5invis/Iosevka/releases/download/v$IOSEVKA_VERSION/PkgTTF-IosevkaTermSS14-$IOSEVKA_VERSION.zip" \
  "$IOSEVKA_SHA256" iosevka.zip
fetch "https://github.com/ryanoasis/nerd-fonts/releases/download/v$NERD_VERSION/FontPatcher.zip" \
  "$NERD_SHA256" FontPatcher.zip

# лицензии — с тех же тегов
curl -sSLf -o "$OUT/LICENSE-Iosevka.md" "https://raw.githubusercontent.com/be5invis/Iosevka/v$IOSEVKA_VERSION/LICENSE.md"
curl -sSLf -o "$OUT/LICENSE-NerdFonts" "https://raw.githubusercontent.com/ryanoasis/nerd-fonts/v$NERD_VERSION/LICENSE"

FACE_NAMES=""
for f in "${FACES[@]}"; do
  IFS=: read -r src dst _ _ <<<"$f"
  FACE_NAMES+="$src:$dst "
done

docker run --rm \
  -v "$CACHE:/cache:ro" -v "$OUT:/out" \
  -e FACE_NAMES="$FACE_NAMES" -e HOST_UID="$(id -u)" -e HOST_GID="$(id -g)" \
  -e SOURCE_DATE_EPOCH="$SOURCE_DATE_EPOCH" \
  "$IMAGE" bash -euo pipefail -c '
    apt-get update -qq
    DEBIAN_FRONTEND=noninteractive apt-get install -y -qq --no-install-recommends \
      fontforge python3-fontforge python3-fonttools python3-brotli unzip >/dev/null
    mkdir -p /work/src /work/patcher /work/patched
    unzip -q /cache/iosevka.zip -d /work/src
    unzip -q /cache/FontPatcher.zip -d /work/patcher
    for pair in $FACE_NAMES; do
      src=${pair%%:*}; dst=${pair##*:}
      echo "patch: $src"
      rm -rf /work/patched/*
      fontforge -quiet -script /work/patcher/font-patcher --complete --quiet \
        --outputdir /work/patched "/work/src/IosevkaTermSS14-$src.ttf" >/dev/null 2>&1
      python3 -c "import sys, glob
from fontTools.ttLib import TTFont
f = TTFont(glob.glob(\"/work/patched/*.ttf\")[0])
f.flavor = \"woff2\"
f.save(sys.argv[1])" "/out/$dst.woff2"
    done
    chown "$HOST_UID:$HOST_GID" /out/*
  '

{
  echo "/* $FAMILY — Iosevka $IOSEVKA_VERSION (Term, SS14) + Nerd Fonts $NERD_VERSION --complete"
  echo "   generated by scripts/build-fonts.sh — do not edit by hand */"
  for f in "${FACES[@]}"; do
    IFS=: read -r _ dst weight style <<<"$f"
    cat <<EOF

@font-face {
  font-family: "$FAMILY";
  src: url("$dst.woff2") format("woff2");
  font-weight: $weight;
  font-style: $style;
  font-display: swap;
}
EOF
  done
} >"$OUT/iosevka.css"

ls -la "$OUT"
