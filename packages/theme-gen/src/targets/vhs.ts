// vhs (charmbracelet/vhs): тема для записей терминала по сценариям .tape — те же цвета
// и шрифт, что в ghostty. В сценарии — абсолютный путь (vhs не раскрывает ~):
//   Source "/home/<user>/.local/share/uiu/vhs/uiu.tape"
// Отличие от ghostty: xterm.js в vhs рисует жирный текст яркими цветами (bold-is-bright),
// и, например, ветки в git log выходят базовыми цветами owo — на белом читаются плохо.

import type { Theme } from "../theme";

/** Семейство шрифта uiu так, как его знает fontconfig (fc-list). */
export const FONT_FAMILY = "IosevkaTermSS 14 Nerd Font";

const ANSI = ["black", "red", "green", "yellow", "blue", "magenta", "cyan", "white"];
const cap = (s: string) => s[0]!.toUpperCase() + s.slice(1);

export function vhsTheme(t: Theme): Record<string, string> {
  const r = (role: string) => t.role(role).hex;
  return {
    name: "uiu light",
    background: r("surface-base"),
    foreground: r("text"),
    cursor: r("text"),
    selection: r("accent-selection"),
    ...Object.fromEntries(ANSI.map((n) => [n, r(`ansi-${n}`)])),
    ...Object.fromEntries(ANSI.map((n) => [`bright${cap(n)}`, r(`ansi-bright-${n}`)])),
  };
}

export function vhs(t: Theme): string {
  return [
    "# uiu — vhs theme (light)",
    "# generated by packages/theme-gen from theme/*.css — do not edit by hand",
    `Set Theme ${JSON.stringify(vhsTheme(t))}`,
    // имя семейства по fontconfig (с пробелом); vhs подставляет его в JS в одинарных
    // кавычках, а в CSS имя с числом «14» без кавычек недопустимо — отсюда '"…"'
    `Set FontFamily '"${FONT_FAMILY}"'`,
    "",
  ].join("\n");
}
