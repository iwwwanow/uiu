// zellij (формат тем 0.42+: компоненты UI, а не 8 цветов). Ставится в
// ~/.local/share/uiu/zellij/uiu.kdl; dotfiles: theme_dir на этот каталог + theme "uiu".
// Тема читается только при старте сервера сессии — см. CLAUDE.md в dotfiles.
//
// Компоненты (у каждого base — текст/линия, background, emphasis_0…3 — выделенные части):
//   text_*      текст плагинов, фон баров (tab-bar, status-bar)
//   ribbon_*    плашки: вкладки в tab-bar, режим и клавиши в status-bar
//   table_*, list_*   session-manager, plugin-manager и прочие плагины
//   frame_*     рамки панелей; exit_code_* — статус командных панелей
// Разметка — как на превью theme/terminal.html: бары chrome, активное — accent-interactive,
// клавиши — тёмные плашки, рамка фокуса — border-strong, остальные — text-disabled.

import type { Theme } from "../theme";

type Component = {
  base: string;
  background: string;
  emphasis: [string, string, string, string];
};

/** Выделения в тексте. По снимкам 0.46: emphasis_0 — модификатор в status-bar («Alt +»),
 *  emphasis_2 — счётчики (Inbox), emphasis_3 — клавиши (Ctrl g, <ENTER>) — чёрным, как на превью. */
const EMPHASIS: Component["emphasis"] = ["accent-match", "text-strong", "state-added", "text-strong"];
const ON_ACCENT: Component["emphasis"] = ["text-on-accent", "text-on-accent", "text-on-accent", "text-on-accent"];

const ANSI = ["black", "red", "green", "yellow", "blue", "magenta", "cyan", "white"];

export const COMPONENTS: Record<string, Component> = {
  text_unselected: { base: "text-muted", background: "surface-chrome", emphasis: EMPHASIS },
  text_selected: { base: "text-strong", background: "accent-menu-selection", emphasis: EMPHASIS },
  ribbon_selected: { base: "text-on-accent", background: "accent-interactive", emphasis: ON_ACCENT },
  ribbon_unselected: { base: "text-on-accent", background: "text-muted", emphasis: ON_ACCENT },
  ribbon_hover: { base: "text-on-accent", background: "text", emphasis: ON_ACCENT },
  table_title: { base: "text-strong", background: "surface-base", emphasis: EMPHASIS },
  table_cell_selected: { base: "text-strong", background: "accent-menu-selection", emphasis: EMPHASIS },
  table_cell_unselected: { base: "text", background: "surface-base", emphasis: EMPHASIS },
  list_selected: { base: "text-strong", background: "accent-menu-selection", emphasis: EMPHASIS },
  list_unselected: { base: "text", background: "surface-base", emphasis: EMPHASIS },
  frame_selected: { base: "border-strong", background: "surface-base", emphasis: EMPHASIS },
  // линию и заголовок zellij красит одним base: на border-subtle (GRAY-91) заголовок
  // неактивной панели не читается — берём GRAY-72
  frame_unselected: { base: "text-disabled", background: "surface-base", emphasis: EMPHASIS },
  frame_highlight: { base: "accent-interactive", background: "surface-base", emphasis: EMPHASIS },
  exit_code_success: { base: "state-added", background: "surface-base", emphasis: EMPHASIS },
  exit_code_error: { base: "state-error", background: "surface-base", emphasis: EMPHASIS },
};

/** Курсоры других участников сессии: тёмные ступени акцентов, затем базовые. */
const PLAYERS = [
  "ansi-blue", "ansi-green", "ansi-yellow", "ansi-magenta", "ansi-red",
  "ansi-cyan", "ansi-bright-red", "ansi-bright-magenta", "ansi-bright-cyan", "ansi-bright-yellow",
];

export function zellij(t: Theme): string {
  // «r g b» из hex — те же значения, что в остальных выходах
  const rgb = (role: string) =>
    [1, 3, 5].map((i) => parseInt(t.role(role).hex.slice(i, i + 2), 16)).join(" ");
  const lines = [
    "// uiu — zellij theme (light)",
    "// generated by packages/theme-gen from theme/*.css — do not edit by hand",
    "themes {",
    "    uiu {",
  ];
  for (const [name, c] of Object.entries(COMPONENTS)) {
    lines.push(`        ${name} {`, `            base ${rgb(c.base)}`, `            background ${rgb(c.background)}`);
    c.emphasis.forEach((e, i) => lines.push(`            emphasis_${i} ${rgb(e)}`));
    lines.push("        }");
  }
  lines.push("        multiplayer_user_colors {");
  PLAYERS.forEach((p, i) => lines.push(`            player_${i + 1} ${rgb(p)}`));
  lines.push("        }", "        terminal_colors {");
  for (const n of ANSI) lines.push(`            ${n} ${rgb(`ansi-${n}`)}`);
  for (const n of ANSI) lines.push(`            bright_${n} ${rgb(`ansi-bright-${n}`)}`);
  lines.push("        }", "    }", "}", "");
  return lines.join("\n");
}
