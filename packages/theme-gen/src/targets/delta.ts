// delta (git-delta, пейджер диффов git): цвета диффа из ролей состояний, как в nvim —
// подложка строки -95, изменённые слова — тёмный знак на той же подложке. Синтаксис —
// ANSI-палитрой терминала (тема bat "ansi"). Подключается из dotfiles:
//   [include] path = ~/.local/share/uiu/delta/uiu.gitconfig
// без файла git include молча пропускает.

import type { Theme } from "../theme";

export function delta(t: Theme): string {
  const r = (role: string) => t.role(role).hex;
  // значение с # в gitconfig — только в кавычках, иначе это комментарий
  const lines: [string, string][] = [
    ["light", "true"],
    ["syntax-theme", "ansi"],
    ["minus-style", `syntax "${r("state-removed-bg")}"`],
    ["minus-emph-style", `"${r("state-removed")}" "${r("state-removed-bg")}"`],
    ["plus-style", `syntax "${r("state-added-bg")}"`],
    ["plus-emph-style", `"${r("state-added")}" "${r("state-added-bg")}"`],
    ["file-style", `"${r("text-strong")}"`],
    ["file-decoration-style", `"${r("border-subtle")}" ul`],
    ["hunk-header-style", "file line-number syntax"],
    ["hunk-header-decoration-style", `"${r("border-subtle")}" box`],
    ["hunk-header-line-number-style", `"${r("text-faint")}"`],
    ["line-numbers-zero-style", `"${r("text-faint")}"`],
    ["line-numbers-minus-style", `"${r("state-removed")}"`],
    ["line-numbers-plus-style", `"${r("state-added")}"`],
    ["line-numbers-left-style", `"${r("border-subtle")}"`],
    ["line-numbers-right-style", `"${r("border-subtle")}"`],
  ];
  return [
    "# uiu — delta colors (light)",
    "# generated by packages/theme-gen from theme/*.css — do not edit by hand",
    "[delta]",
    ...lines.map(([k, v]) => `\t${k} = ${v}`),
    "",
  ].join("\n");
}
