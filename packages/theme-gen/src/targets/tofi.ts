// tofi (лаунчер Wayland, $mod+o, cliphist, пароли): только цвета — шрифт и размеры в dotfiles.
// Уровень overlay, как Telescope в nvim. Подключается из ~/.config/tofi/config первой строкой:
//   include = ../../.local/share/uiu/tofi/uiu.conf
// tofi считает путь от каталога конфига, ~ не раскрывает; без файла пишет ошибку и
// работает со своими цветами. Опции после include перекрывают его.

import type { Theme } from "../theme";

export const OPTIONS: [string, string][] = [
  ["background-color", "surface-overlay"],
  ["border-color", "border-strong"],
  ["outline-color", "border-strong"],
  ["text-color", "text"],
  ["prompt-color", "text-faint"],
  ["placeholder-color", "text-disabled"],
  ["input-color", "text-strong"],
  ["default-result-color", "text"],
  ["alternate-result-color", "text"],
  ["selection-color", "text-strong"],
  ["selection-background", "accent-menu-selection"],
  ["selection-match-color", "accent-match"],
  ["text-cursor-color", "text-strong"],
];

export function tofi(t: Theme): string {
  return [
    "# uiu — tofi colors (light)",
    "# generated by packages/theme-gen from theme/*.css — do not edit by hand",
    ...OPTIONS.map(([k, role]) => `${k} = ${t.role(role).hex}`),
    "",
  ].join("\n");
}
