// dunst (уведомления): только цвета — шрифт, размеры, таймауты в dotfiles.
// Уровень overlay с рамкой, как плавающие окна nvim и tooltip waybar; критические —
// белым по красному, как критический заряд в waybar.
// Подключается drop-in файлом: симлинк ~/.config/dunst/dunstrc.d/uiu.conf →
// ~/.local/share/uiu/dunst/uiu.conf. dunst читает dunstrc.d/ после dunstrc (ключи
// перекрывают), на висячий симлинк — только предупреждение.

import type { Theme } from "../theme";

export const SECTIONS: Record<string, Record<string, string>> = {
  global: { frame_color: "border-strong", highlight: "accent-interactive" },
  urgency_low: { background: "surface-overlay", foreground: "text-muted", frame_color: "border-strong" },
  urgency_normal: { background: "surface-overlay", foreground: "text", frame_color: "border-strong" },
  urgency_critical: { background: "state-error", foreground: "text-on-accent", frame_color: "state-error" },
};

export function dunst(t: Theme): string {
  const out = ["# uiu — dunst colors (light)", "# generated by packages/theme-gen from theme/*.css — do not edit by hand"];
  for (const [section, keys] of Object.entries(SECTIONS)) {
    out.push("", `[${section}]`, ...Object.entries(keys).map(([k, role]) => `    ${k} = "${t.role(role).hex}"`));
  }
  return out.join("\n") + "\n";
}
