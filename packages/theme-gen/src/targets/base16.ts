// base16 (tinted-theming, scheme format 0.11): мост для программ, у которых нет своей
// темы uiu, — через шаблоны tinted-theming (tinty). Терминальный софт уже берёт
// ANSI-палитру из ghostty; base16 — для остального.
//
// base00–07 — серая шкала от фона к тексту (светлая тема: base00 — фон, base07 — самое тёмное).
// base08–0F — тёмные ступени акцентов, как ANSI normal: читаются как текст на белом.

import type { Theme } from "../theme";

export const SLOTS: [string, string][] = [
  ["base00", "surface-base"], // фон
  ["base01", "surface-chrome"], // статусбары, номера строк
  ["base02", "accent-menu-selection"], // выделение
  ["base03", "syntax-comment"], // комментарии, невидимые символы
  ["base04", "text-faint"], // тёмный текст статусбаров
  ["base05", "text"], // основной текст
  ["base06", "text-strong"],
  ["base07", "text-strong"],
  ["base08", "ansi-red"], // переменные, удалённое в diff
  ["base09", "ansi-yellow"], // числа, константы (yellow → ORANGE-50)
  ["base0A", "ansi-yellow"], // классы, фон поиска
  ["base0B", "ansi-green"], // строки, добавленное в diff
  ["base0C", "ansi-cyan"], // escape, regex (cyan → BLUE-50)
  ["base0D", "ansi-blue"], // функции (BLUE-DARK)
  ["base0E", "ansi-magenta"], // ключевые слова
  ["base0F", "ansi-red"], // устаревшее
];

export function base16(t: Theme): string {
  return [
    "# uiu — base16 scheme (light)",
    "# generated by packages/theme-gen from theme/*.css — do not edit by hand",
    'system: "base16"',
    'name: "uiu light"',
    'slug: "uiu-light"',
    'author: "iwwwanow"',
    'variant: "light"',
    "palette:",
    ...SLOTS.map(([slot, role]) => `  ${slot}: "${t.role(role).hex}" # ${role}`),
    "",
  ].join("\n");
}
